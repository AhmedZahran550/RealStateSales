-- ==============================================================================
-- مشروع الواحة (El Waha) - سكريبت إنشاء الجداول والأنواع (Database Schema)
-- Supabase PostgreSQL Schema (Pure DDL - No Seed Data)
-- ==============================================================================

BEGIN;

-- ------------------------------------------------------------------------------
-- 0. تنظيف الجداول والأنواع القديمة (Drop Existing Tables & Types)
-- ------------------------------------------------------------------------------
DROP TABLE IF EXISTS customer_activities CASCADE;
DROP TABLE IF EXISTS customer_units CASCADE;
DROP TABLE IF EXISTS customers CASCADE;
DROP TABLE IF EXISTS unit_media CASCADE;
DROP TABLE IF EXISTS unit_history CASCADE;
DROP TABLE IF EXISTS units CASCADE;
DROP TABLE IF EXISTS buildings CASCADE;
DROP TABLE IF EXISTS zones CASCADE;
DROP TABLE IF EXISTS profiles CASCADE;
DROP TABLE IF EXISTS companies CASCADE;

DROP TYPE IF EXISTS app_role CASCADE;
DROP TYPE IF EXISTS unit_status CASCADE;
DROP TYPE IF EXISTS unit_kind CASCADE;
DROP TYPE IF EXISTS media_kind CASCADE;
DROP TYPE IF EXISTS customer_stage CASCADE;
DROP TYPE IF EXISTS activity_type CASCADE;

-- ------------------------------------------------------------------------------
-- 1. الأنواع والتصنيفات (Custom Enum Types)
-- ------------------------------------------------------------------------------
CREATE TYPE app_role AS ENUM ('super_admin', 'company_admin', 'user', 'admin');
CREATE TYPE unit_status AS ENUM ('available', 'reserved', 'sold');
CREATE TYPE unit_kind AS ENUM ('duplex', 'ground_garden', 'floor_1', 'floor_2', 'floor_3', 'roof', 'other');
CREATE TYPE media_kind AS ENUM ('image', 'video', 'link');
CREATE TYPE customer_stage AS ENUM ('lead', 'asking', 'viewed', 'negotiating', 'reserved', 'closed', 'lost');
CREATE TYPE activity_type AS ENUM ('call', 'whatsapp', 'visit', 'note', 'stage_change');

-- ------------------------------------------------------------------------------
-- 2. تعريف الجداول الأساسية (Tables Definition)
-- ------------------------------------------------------------------------------

-- الشركات العقارية (Companies)
CREATE TABLE companies (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  commercial_name text,
  logo_url text,
  phone text,
  email text,
  address text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- المستخدمون والملفات الشخصية (Profiles)
CREATE TABLE profiles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid REFERENCES companies(id) ON DELETE CASCADE,
  full_name text NOT NULL,
  username text NOT NULL UNIQUE,
  password text NOT NULL,
  phone text UNIQUE,
  role app_role NOT NULL DEFAULT 'user',
  created_at timestamptz DEFAULT now()
);

-- مناطق كل شركة (رئيسية ومناطق فرعية بامتلاك شركة + مستويين)
CREATE TABLE zones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id uuid NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  parent_id bigint REFERENCES zones(id) ON DELETE CASCADE,
  name text NOT NULL,
  direction text,
  map_x numeric,
  map_y numeric,
  notes text
);
CREATE UNIQUE INDEX zones_company_name_idx ON zones (company_id, name);
CREATE INDEX zones_parent_idx ON zones (parent_id);

-- المباني والقطع (Buildings)
CREATE TABLE buildings (
  id bigint PRIMARY KEY,
  company_id uuid REFERENCES companies(id) ON DELETE CASCADE,
  zone_id bigint NOT NULL REFERENCES zones(id) ON DELETE CASCADE,
  plot_no int NOT NULL,
  land_area numeric,
  features text[] DEFAULT '{}',
  map_x numeric,
  map_y numeric,
  notes text
);

-- الوحدات العقارية (Units)
CREATE TABLE units (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  building_id bigint NOT NULL REFERENCES buildings(id) ON DELETE CASCADE,
  unit_kind unit_kind NOT NULL,
  floor smallint,
  side text,
  area numeric NOT NULL,
  garden_area numeric,
  price numeric NOT NULL,
  negotiable boolean DEFAULT false,
  delivery_note text,
  payment_terms text,
  description text,
  status unit_status DEFAULT 'available',
  features text[] DEFAULT '{}',
  lat numeric,
  lng numeric,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- سجل تعديلات وحالات الوحدة (Unit History)
CREATE TABLE unit_history (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  unit_id uuid NOT NULL REFERENCES units(id) ON DELETE CASCADE,
  changed_by uuid REFERENCES profiles(id) ON DELETE SET NULL,
  change_type text NOT NULL,
  old_status unit_status,
  new_status unit_status,
  details text,
  changes jsonb,
  created_at timestamptz DEFAULT now()
);

-- معرض وسائط الوحدات (Unit Media)
CREATE TABLE unit_media (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  unit_id uuid NOT NULL REFERENCES units(id) ON DELETE CASCADE,
  owner_id uuid REFERENCES profiles(id) ON DELETE SET NULL,
  kind media_kind NOT NULL DEFAULT 'image',
  storage_path text,
  external_url text,
  caption text,
  sort_order int DEFAULT 0,
  size_bytes bigint,
  created_at timestamptz DEFAULT now()
);

-- إدارة العملاء (CRM Customers)
CREATE TABLE customers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  name text NOT NULL,
  phone text NOT NULL,
  whatsapp text,
  budget numeric,
  source text,
  stage customer_stage NOT NULL DEFAULT 'lead',
  next_followup_at timestamptz,
  notes text,
  deleted_at timestamptz,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- ربط العملاء بالوحدات المهتمين بها (Customer Units)
CREATE TABLE customer_units (
  customer_id uuid REFERENCES customers(id) ON DELETE CASCADE,
  unit_id uuid REFERENCES units(id) ON DELETE CASCADE,
  PRIMARY KEY (customer_id, unit_id)
);

-- سجل أنشطة ومتابعات العملاء (Customer Activities)
CREATE TABLE customer_activities (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id uuid NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  type activity_type NOT NULL,
  note text NOT NULL,
  created_at timestamptz DEFAULT now()
);

-- ------------------------------------------------------------------------------
-- 3. الفهارس لتسريع الاستعلامات (Indexes)
-- ------------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_profiles_company_id ON profiles(company_id);
CREATE INDEX IF NOT EXISTS idx_buildings_company_id ON buildings(company_id);
CREATE INDEX IF NOT EXISTS idx_buildings_zone_id ON buildings(zone_id);
CREATE INDEX IF NOT EXISTS idx_units_company_id ON units(company_id);
CREATE INDEX IF NOT EXISTS idx_units_building_id ON units(building_id);
CREATE INDEX IF NOT EXISTS idx_units_status ON units(status);
CREATE INDEX IF NOT EXISTS idx_unit_history_unit_id ON unit_history(unit_id);
CREATE INDEX IF NOT EXISTS idx_unit_media_unit_id ON unit_media(unit_id);
CREATE INDEX IF NOT EXISTS idx_customers_owner_id ON customers(owner_id);
CREATE INDEX IF NOT EXISTS idx_customers_stage ON customers(stage);
CREATE INDEX IF NOT EXISTS idx_customer_activities_customer_id ON customer_activities(customer_id);

-- ------------------------------------------------------------------------------
-- 4. إعدادات الحماية والأمان (Row Level Security & Permissions)
-- ------------------------------------------------------------------------------
-- تعطيل Row Level Security (RLS) لأن الحماية والتوثيق يتم إدارتهما عبر Next.js Server & Middleware
ALTER TABLE companies DISABLE ROW LEVEL SECURITY;
ALTER TABLE profiles DISABLE ROW LEVEL SECURITY;
ALTER TABLE zones DISABLE ROW LEVEL SECURITY;
ALTER TABLE buildings DISABLE ROW LEVEL SECURITY;
ALTER TABLE units DISABLE ROW LEVEL SECURITY;
ALTER TABLE unit_history DISABLE ROW LEVEL SECURITY;
ALTER TABLE unit_media DISABLE ROW LEVEL SECURITY;
ALTER TABLE customers DISABLE ROW LEVEL SECURITY;
ALTER TABLE customer_units DISABLE ROW LEVEL SECURITY;
ALTER TABLE customer_activities DISABLE ROW LEVEL SECURITY;

-- منح الصلاحيات للأدوار المستخدمة في سوبابيز
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL ROUTINES IN SCHEMA public TO anon, authenticated, service_role;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON ROUTINES TO anon, authenticated, service_role;

COMMIT;
