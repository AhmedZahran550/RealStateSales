-- ==============================================================================
-- ترحيل المناطق لكل شركة + ربط سابقة الأعمال بالمباني
-- Per-company areas + past-work linked to buildings (not units)
--
-- ينفَّذ مرة واحدة على قاعدة البيانات الحالية (SQL Editor في Supabase).
-- بعد هذا الترحيل:
--   * كل منطقة مملوكة لشركة (company_id NOT NULL)
--   * الشركة الوحيدة الموجودة حاليًا تحصل على المناطق الافتراضية الـ16 الحالية
--   * أي شركة جديدة تبدأ بلا مناطق — يضيف مدير الشركة مناطقه بنفسه
--   * لا يمكن حذف منطقة بها مبانٍ (يُمنع على مستوى الـ API)
--   * company_gallery_items.building_id: سابقة الأعمال ترتبط بالمبنى (القطعة)
--
-- ملحوظة: relation "zones" قد يكون قد وُجد بدون RLS (كما في complete_schema_and_seed.sql) —
-- لا نغير إعدادات RLS هنا؛ الحماية تُنفذ على مستوى الـ API (/api/zones).
-- ==============================================================================

BEGIN;

-- ------------------------------------------------------------------------------
-- PART A — مناطق لكل شركة
-- ------------------------------------------------------------------------------

-- A.1 عمود الشركة
ALTER TABLE zones ADD COLUMN IF NOT EXISTS company_id uuid REFERENCES companies(id) ON DELETE CASCADE;

-- A.2 تحويل id إلى bigint (كان smallint 1..16) وإنشاء تسلسل تلقائي للمناطق الجديدة
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'zones' AND column_name = 'id' AND data_type = 'bigint'
  ) THEN
    ALTER TABLE zones ALTER COLUMN id TYPE bigint;
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'zones' AND column_name = 'id' AND is_identity = 'YES'
  ) THEN
    ALTER TABLE zones ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 17 RESTART WITH 17);
  END IF;
END $$;

-- A.3 إسناد المناطق الافتراضية الحالية (بروابط المباني القائمة) للشركة الوحيدة الموجودة
DO $$
DECLARE
  target uuid;
BEGIN
  SELECT COALESCE(
    (SELECT b.company_id FROM buildings b WHERE b.company_id IS NOT NULL LIMIT 1),
    (SELECT c.id FROM companies c LIMIT 1)
  ) INTO target;

  IF target IS NOT NULL THEN
    UPDATE zones SET company_id = target WHERE company_id IS NULL;
  END IF;
END $$;

-- A.4 المنطقة بلا شركة غير مسموح (الشركات الجديدة تبدأ بلا مناطق ويضيفها مديرها)
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'zones' AND column_name = 'company_id' AND is_nullable = 'YES'
  ) THEN
    ALTER TABLE zones ALTER COLUMN company_id SET NOT NULL;
  END IF;
END $$;

-- A.5 توسيع العمود المرجعي في buildings ليطابق bigint
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'buildings' AND column_name = 'zone_id' AND data_type = 'bigint'
  ) THEN
    ALTER TABLE buildings ALTER COLUMN zone_id TYPE bigint;
  END IF;
END $$;

-- A.6 فهرس: أسماء المناطق فريدة داخل كل شركة
CREATE UNIQUE INDEX IF NOT EXISTS zones_company_name_idx ON zones (company_id, name);

-- ------------------------------------------------------------------------------
-- PART B — سابقة الأعمال مرتبطة بالمباني
-- ------------------------------------------------------------------------------

ALTER TABLE company_gallery_items ADD COLUMN IF NOT EXISTS building_id bigint REFERENCES buildings(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_gallery_building ON company_gallery_items (company_id, building_id);

COMMIT;
